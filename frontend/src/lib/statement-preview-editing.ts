import type { BankStatement, StatementTransaction } from '@/services/statement-exports';
import type { CellKind } from '@/components/statement-editable-cell';
import type { EditableTransactionField } from './statement-row-editing';

export type PreviewEditTarget = {
  scope: 'statement' | 'transaction';
  field: keyof BankStatement | EditableTransactionField;
  value: string | number | null | undefined;
  kind: CellKind;
  signed?: boolean;
};
const transactionFields: Record<string, EditableTransactionField> = {
  Date: 'date',
  ValueDate: 'valueDate',
  Description: 'description',
  MovementDescription: 'description',
  DescriptionWithBalances: 'description',
  Reference: 'reference',
  Debit: 'debit',
  Credit: 'credit',
  Amount: 'amount',
  Direction: 'direction',
  Balance: 'balance',
  Currency: 'currency',
  Journal: 'journal',
  Account: 'account',
  Analytic: 'analytic',
  RecordType: 'recordType',
};
const statementFields: Record<string, keyof BankStatement> = {
  BankCode: 'bankCode',
  StatementNumber: 'statementNumber',
  OpeningBalance: 'openingBalance',
  ClosingBalance: 'closingBalance',
};
export function cellKind(field: string): CellKind {
  if (/date$/i.test(field)) return 'date';
  if (/^(debit|credit|amount|balance|openingBalance|closingBalance)$/.test(field)) return 'money';
  if (field === 'direction') return 'direction';
  if (field === 'currency') return 'currency';
  return 'text';
}

export function previewEditTarget(
  statement: BankStatement,
  row: StatementTransaction | undefined,
  source: string,
  rowKind: string,
  modelType: string,
): PreviewEditTarget | null {
  const sage = modelType === 'SAGEX3';
  const balance = rowKind === 'OPENING_BALANCE' || rowKind === 'CLOSING_BALANCE';
  // These values are generated by SageX3Rows, not editable source fields.
  if (source === 'Sequence' || (sage && ['RecordType', 'StatementNumber'].includes(source)))
    return null;
  let field: keyof BankStatement | EditableTransactionField | undefined;
  let scope: 'statement' | 'transaction' = 'statement';
  if (sage && balance) {
    const opening = rowKind === 'OPENING_BALANCE';
    if (source === 'Date') field = opening ? 'openingBalanceDate' : 'closingBalanceDate';
    else if (source === 'ValueDate')
      field = opening ? 'openingBalanceValueDate' : 'closingBalanceValueDate';
    else if (source === 'Amount') field = opening ? 'openingBalance' : 'closingBalance';
    else if (source === 'DescriptionWithBalances')
      field = opening ? 'openingBalanceDescription' : 'closingBalanceDescription';
    else if (['Currency', 'Journal', 'Account', 'Analytic'].includes(source))
      field = transactionFields[source];
    else field = statementFields[source];
  } else if (sage && source === 'Currency') field = 'currency';
  else if (statementFields[source]) field = statementFields[source];
  else if (row && transactionFields[source]) {
    field = transactionFields[source];
    scope = 'transaction';
  }
  if (!field) return null;
  let value =
    scope === 'transaction'
      ? row![field as EditableTransactionField]
      : statement[field as keyof BankStatement];
  if (
    scope === 'transaction' &&
    ['currency', 'journal', 'account', 'analytic', 'recordType'].includes(field)
  )
    value ??= statement[field as keyof BankStatement];
  if (field === 'amount' && row && (row.debit != null) !== (row.credit != null))
    value ??= row.debit ?? row.credit;
  if (field === 'openingBalanceDate') value ??= statement.periodStart;
  if (field === 'closingBalanceDate') value ??= statement.periodEnd;
  if (field === 'openingBalanceValueDate')
    value ??= statement.openingBalanceDate ?? statement.periodStart;
  if (field === 'closingBalanceValueDate')
    value ??= statement.closingBalanceDate ?? statement.periodEnd;
  return {
    scope,
    field,
    value: value as string | number | null | undefined,
    kind: cellKind(field),
    signed: ['balance', 'openingBalance', 'closingBalance'].includes(field),
  };
}
